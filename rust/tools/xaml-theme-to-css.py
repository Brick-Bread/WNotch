"""Turns Notch's base theme dictionaries (src/Notch.App/Themes) into CSS custom properties for the
Svelte UI, so the colours, fonts and radii stay exactly the C# app's.

    python3 rust/tools/xaml-theme-to-css.py > rust/ui/src/theme/base.css

Each resource key becomes a variable named after it: `IslandBrush` is `--island`,
`CardRadius` is `--card-radius`, `UiFontFamily` is `--ui-font-family`. Plugin themes are translated
to the same names, so a theme sets exactly the variables it defines and inherits the rest.
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

THEMES = Path(__file__).resolve().parents[2] / "src" / "Notch.App" / "Themes"
X = "{http://schemas.microsoft.com/winfx/2006/xaml}"

# WPF font paths into the app's assets become the bundled families declared in fonts.css.
FONT_PATHS = {"/Assets/Fonts/#Inter": "Inter", "/Assets/Fonts/#Inter Display": "Inter Display"}


def variable(key):
    key = re.sub(r"Brush$", "", key)
    return "--" + re.sub(r"(?<!^)(?=[A-Z])", "-", key).lower()


def color(text):
    """WPF #AARRGGBB or #RRGGBB as CSS #RRGGBBAA or #RRGGBB."""
    hex_ = text.strip().lstrip("#")
    if len(hex_) == 8:
        return "#" + hex_[2:] + hex_[:2]
    return "#" + hex_


def font(text):
    families = []
    for part in text.split(","):
        part = FONT_PATHS.get(part.strip(), part.strip())
        families.append(f'"{part}"' if " " in part else part)
    return ", ".join(families)


def declarations(file):
    for element in ET.parse(THEMES / file).getroot():
        key = element.get(X + "Key")
        tag = element.tag.split("}")[-1]
        if tag == "SolidColorBrush":
            yield variable(key), color(element.get("Color"))
        elif tag == "FontFamily":
            yield variable(key), font(element.text)
        elif tag == "CornerRadius":
            yield variable(key), f"{element.text.strip()}px"
        elif tag == "Double":
            value = element.text.strip()
            yield variable(key), f"{value}px" if key.endswith("FontSize") else value
        else:
            raise SystemExit(f"{file}: {tag} {key} has no CSS form; add one here")


def block(selector, file):
    lines = [f"{selector} {{"] + [f"  {name}: {value};" for name, value in declarations(file)] + ["}"]
    return "\n".join(lines)


def main():
    dark = dict(declarations("Dark.xaml"))
    light = dict(declarations("Light.xaml"))
    if dark.keys() != light.keys():
        raise SystemExit("Dark.xaml and Light.xaml define different keys")

    out = [
        "/* Generated by rust/tools/xaml-theme-to-css.py from src/Notch.App/Themes. Do not edit by hand. */",
        "",
        block(":root", "Design.xaml"),
        "",
        block(':root,\n[data-theme="dark"]', "Dark.xaml"),
        "",
        block('[data-theme="light"]', "Light.xaml"),
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
